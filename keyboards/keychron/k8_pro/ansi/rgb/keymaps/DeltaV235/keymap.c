bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    static bool h_pressed = false;
    static bool ctrl_pressed = false;
    static uint8_t saved_mods = 0;

    // 跟踪 Ctrl 键状态
    if (keycode == KC_LCTL || keycode == KC_RCTL) {
        if (record->event.pressed) {
            ctrl_pressed = true;
        } else {
            ctrl_pressed = false;
            // 如果松开 Ctrl 键，确保停止 Backspace
            if (h_pressed) {
                unregister_code(KC_BSPC);
                h_pressed = false;
            }
        }
        return true; // 正常处理 Ctrl 键
    }

    // 处理 H 键
    if (keycode == KC_H) {
        // 获取当前修饰键状态
        uint8_t mods = get_mods();

        if (record->event.pressed) {
            // H 键被按下
            if (ctrl_pressed || (mods & MOD_MASK_CTRL)) {
                // 按下了 H 且 Ctrl 已按下
                h_pressed = true;
                saved_mods = mods; // 保存修饰键状态

                // 临时清除修饰键
                clear_mods();

                // 发送 Backspace
                register_code(KC_BSPC);

                return false; // 拦截该按键
            }
        } else {
            // H 键被释放
            if (h_pressed) {
                // 停止 Backspace
                unregister_code(KC_BSPC);
                h_pressed = false;

                // 恢复之前保存的修饰键状态
                set_mods(saved_mods);

                return false; // 拦截该按键
            }
        }
    }

    // 如果按下了其他键，确保停止 Backspace
    if (h_pressed && keycode != KC_H && keycode != KC_LCTL && keycode != KC_RCTL) {
        unregister_code(KC_BSPC);
        h_pressed = false;
        set_mods(saved_mods);
    }

    return true; // 正常处理所有其他按键
}
